export async function createSampleSaralWorkbookBuffer() {
  const wb = new ExcelJS.Workbook();
  wb.creator = 'Saral PayPack';
  wb.created = new Date();

  const ws = wb.addWorksheet('Salary Rate');

  ws.getCell('A1').value = 'Salary Structure:  2025 April';
  ws.getCell('A2').value = 'Month/Year:  Sep/2026';

  const headers = [
    'SLNO', 'Ref. No.', 'Name', 'BASIC', 'DA', 'HRA', 'Wash allow', 'Var Allow',
    'Others', 'OT allow', 'Leave Pay', 'Bonus Pay', 'NH', 'Std Ded.', 'Add.4 hour',
    'W/O Relei.', 'GRATUITY', 'BONUS.', 'LEAVE PAY.', 'TOOLS AND', 'Serv Charg',
    'StaffWelfr', 'Other Coll', 'Uniform Cl', 'Training', 'LiasonChrg', 'NH.',
    'OTLY INC A', 'Bill AMT', 'GMC', 'ACC FLAG', 'PF Vol. (%)', 'PF Vol (%)',
    'PF Vol', 'Remarks'
  ];

  const headerRow = ws.getRow(3);
  headers.forEach((h, idx) => {
    const cell = headerRow.getCell(idx + 1);
    cell.value = h;
    cell.font = { name: 'Calibri', size: 10, bold: true, color: { argb: 'FFFFFFFF' } };
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF1E293B' } };
    cell.alignment = { horizontal: 'center', vertical: 'middle' };
  });
  headerRow.height = 24;

  SAMPLE_EMPLOYEES.forEach((emp, i) => {
    const row = ws.getRow(i + 4);
    const rowValues = [
      emp.slno || (i + 1),
      emp.employeeId,
      emp.employeeName,
      emp.basic,
      emp.da,
      emp.hra,
      emp.washingAllowance,
      emp.variableAllowance,
      emp.others ?? 0,
      emp.otAllow ?? 0,
      emp.leavePay ?? 0,
      emp.bonusPay ?? 0,
      emp.nh ?? 0,
      emp.standardDeduction ?? 0,
      emp.add4Hour ?? 0,
      emp.woRelei ?? 0,
      emp.gratuity ?? 0,
      emp.bonusDot ?? 0,
      emp.leavePayDot ?? 0,
      emp.toolsAnd ?? 0,
      emp.servCharg ?? 0,
      emp.staffWelfr ?? 0,
      emp.otherColl ?? 0,
      emp.uniformCl ?? 0,
      emp.training ?? 0,
      emp.liasonChrg ?? 0,
      emp.nhDot ?? 0,
      emp.otlyIncA ?? 0,
      emp.ctc ?? 0,
      emp.gmc ?? 0,
      emp.accFlag ?? 0,
      emp.pfVolPct ?? 'No',
      emp.pfVolPctNum ?? 0,
      emp.pfVol ?? 0,
      emp.remarks ?? ''
    ];

    rowValues.forEach((val, idx) => {
      const cell = row.getCell(idx + 1);
      cell.value = val;
      cell.font = { name: 'Calibri', size: 10 };
      if (typeof val === 'number' && idx >= 3) {
        cell.numFmt = '#,##0.00';
        cell.alignment = { horizontal: 'right', vertical: 'middle' };
      } else {
        cell.alignment = { horizontal: idx < 2 ? 'center' : 'left', vertical: 'middle' };
      }
    });
    row.height = 20;
  });

  return await wb.xlsx.writeBuffer();
}
